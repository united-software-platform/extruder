package application

import "errors"

// ErrTargetDirUnsuitable — целевой каталог непригоден: не существует, не является каталогом либо
// недоступен текущему процессу на запись. Отказ принадлежит контракту: вызывающая сторона
// отличает непригодный каталог от прочих отказов, не зная, как проверялась пригодность.
var ErrTargetDirUnsuitable = errors.New("целевой каталог непригоден")

// TargetDirectory — контракт целевого каталога: перечислить содержимое и проверить пригодность
// к записи. Сам путь приходит параметром, а не хранится реализацией: так сценарий проверяется
// на временном каталоге теста, а точка монтирования остаётся делом точки входа.
//
// Контракт объявлен в слое приложения, а не в домене: его реализация обязана обратиться
// к файловой системе.
type TargetDirectory interface {
	// EnsureWritable проверяет, что каталог существует, является каталогом и доступен процессу
	// на запись. Непригодность возвращается ошибкой, сравнимой с ErrTargetDirUnsuitable
	// и называющей причину.
	EnsureWritable(dir string) error
	// Entries возвращает имена элементов верхнего уровня каталога без обхода вложенных.
	Entries(dir string) ([]string, error)
}
