package application

import (
	"errors"
	"strings"
)

// ErrInputInterrupted — поток стандартного ввода кончился до того, как дан ответ на очередной
// вопрос. Отказ принадлежит контракту опроса, а не его реализации: вызывающая сторона отличает
// прерванный ввод от решения человека, не зная, откуда читались ответы.
var ErrInputInterrupted = errors.New("ввод прерван")

// Prompter — контракт опроса: три операции, которыми сценарий задаёт вопросы, не зная ни о потоках
// ввода-вывода, ни о нумерации пунктов.
//
// Контракт объявлен в слое приложения, а не в домене: его реализация обязана обратиться
// к окружению. Текст подсказки печатается перед чтением ответа как есть — сценарий складывает
// в него и сам вопрос, и причину отказа предыдущего ответа, и сводку.
//
// Разбор ответа — дело реализации: неразобранный ответ на вопрос со списком она печатает причиной
// и предъявляет тот же вопрос снова, поэтому SelectOne и SelectMany возвращают либо разобранный
// ответ, либо ошибку. Строка из ReadLine возвращается как есть: решение, годна ли она, принимает
// сценарий, и он же переспрашивает.
type Prompter interface {
	// SelectOne задаёт вопрос с выбором одного пункта и возвращает его номер, считая от нуля.
	SelectOne(prompt string, options []string) (int, error)
	// SelectMany задаёт вопрос с выбором нескольких пунктов и возвращает их номера, считая
	// от нуля: без повторов, в порядке перечисления пунктов.
	SelectMany(prompt string, options []string) ([]int, error)
	// ReadLine печатает подсказку и возвращает прочитанную строку без обрамляющих пробелов.
	ReadLine(prompt string) (string, error)
}

// Ответ, означающий согласие. Умолчанием у вопросов о продолжении стоит «нет»: пустой ответ
// и любой ответ, кроме «да», означают отказ.
const answerYes = "да"

// confirms отвечает, означает ли ответ согласие. Регистр ответа не учитывается.
func confirms(answer string) bool {
	return strings.EqualFold(strings.TrimSpace(answer), answerYes)
}

// options приводит словарь измерения к пунктам списка. Имена значений печатаются строками
// словаря без преобразования регистра и разделителей.
func options[T ~string](values []T) []string {
	items := make([]string, 0, len(values))

	for _, value := range values {
		items = append(items, string(value))
	}

	return items
}
