package infrastructure

import "os"

// Stater — источник сведений о потоке. Его реализует `*os.File`, поэтому проверка терминала
// выполняется и на стандартном вводе, и на обычном файле теста.
type Stater interface {
	Stat() (os.FileInfo, error)
}

// IsTerminal отвечает, является ли поток терминалом. Проверяется только стандартный ввод:
// перенаправить стандартный вывод в файл — законный сценарий, и отказывать из-за него нельзя.
// Поток, о котором не удалось получить сведения, терминалом не считается: опрос на нём либо
// виснет, либо падает на первом же вопросе, и отказ до первого вопроса — меньшее из двух.
func IsTerminal(stream Stater) bool {
	info, err := stream.Stat()
	if err != nil {
		return false
	}

	return info.Mode()&os.ModeCharDevice != 0
}
