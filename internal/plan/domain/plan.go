package domain

// Layer — слой модуля с ролями внутри.
type Layer struct {
	Kind  LayerKind
	Roles []Role
}

// Module — модуль создаваемого проекта. Имени у модуля нет: пока модуль один, различать
// нечего, а имя понадобится, когда модулей станет несколько.
type Module struct {
	Layers []Layer
}

// Plan — план структуры: контракт между фазой построения и бэкендом рендеринга.
//
// Роли уровня проекта вынесены отдельным полем, а не приписаны псевдослою: манифест модуля,
// точка входа и цель сборки не принадлежат ни домену, ни приложению, ни инфраструктуре,
// и псевдослой пришлось бы отфильтровывать в каждом бэкенде.
type Plan struct {
	Modules      []Module
	ProjectRoles []Role
}
